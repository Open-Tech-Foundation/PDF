#!/usr/bin/env python3
"""Generate crates/otf-pdf-font/src/tables.rs from pdf.js's font data.

The data, all Apache-2.0 (Copyright Mozilla Foundation), is:
  glyphlist.js       glyph name -> Unicode (Adobe Glyph List and extensions)
  encodings.js       Standard, WinAnsi, MacRoman, Symbol, ZapfDingbats encodings
  metrics.js         glyph widths of the standard 14 fonts (Adobe AFM data)
  standard_fonts.js  aliases of common font names to the standard 14

It is converted, not hand-copied, so the tables can be checked against the
source: `tsr fonts:tables` regenerates and fails on any difference.

    scripts/generate-font-tables.py [pdfjs-src-dir]

Without a directory, the files are downloaded at the commit pinned for the
pdf.js corpus in corpus/sources.tsv.
"""

import re
import sys
import urllib.request
from pathlib import Path

root = Path(__file__).resolve().parent.parent
out_path = root / "crates" / "otf-pdf-font" / "src" / "tables.rs"
FILES = ["glyphlist", "encodings", "metrics", "standard_fonts"]


def commit():
    for line in (root / "corpus" / "sources.tsv").read_text().splitlines():
        if line.startswith("pdfjs\t"):
            return line.split("\t")[2]
    raise SystemExit("no pdfjs commit in corpus/sources.tsv")


def load(src_dir):
    texts = {}
    for name in FILES:
        if src_dir:
            texts[name] = (Path(src_dir) / f"{name}.js").read_text(encoding="utf-8")
        else:
            url = f"https://raw.githubusercontent.com/mozilla/pdf.js/{commit()}/src/core/{name}.js"
            texts[name] = urllib.request.urlopen(url).read().decode("utf-8")
    return texts


def rust_str(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):x}}}")
    return '"' + "".join(out) + '"'


def key(raw):
    # t.name, t["name"]
    return raw[1:-1] if raw.startswith('"') else raw


def glyph_list(js):
    body = js[js.index("getGlyphsUnicode"):js.index("getDingbatsGlyphsUnicode")]
    entries = {}
    for m in re.finditer(r'^\s*t(?:\.([A-Za-z0-9_]+)|\[("[^"]+")\]) = (0x[0-9a-fA-F]+|\[[^\]]*\]);', body, re.M):
        name = m.group(1) or key(m.group(2))
        value = m.group(3)
        if value.startswith("["):
            chars = "".join(chr(int(v, 16)) for v in re.findall(r"0x[0-9a-fA-F]+", value))
        else:
            chars = chr(int(value, 16))
        entries[name] = chars
    return sorted(entries.items(), key=lambda kv: kv[0].encode())


def dingbats_list(js):
    body = js[js.index("getDingbatsGlyphsUnicode"):]
    entries = {}
    for m in re.finditer(r'^\s*t(?:\.([A-Za-z0-9_]+)|\[("[^"]+")\]) = (0x[0-9a-fA-F]+);', body, re.M):
        entries[m.group(1) or key(m.group(2))] = chr(int(m.group(3), 16))
    return sorted(entries.items(), key=lambda kv: kv[0].encode())


def encoding(js, name):
    start = js.index(f"const {name} = [")
    body = js[start:js.index("];", start)]
    names = re.findall(r'"([^"]*)"', body)
    assert len(names) == 256, (name, len(names))
    return names


def metrics(js):
    fonts = {}
    for m in re.finditer(r'^  t(?:\.([A-Za-z]+)|\["([A-Za-z-]+)"\]) = (\d+);', js, re.M):
        fonts[m.group(1) or m.group(2)] = int(m.group(3))
    for m in re.finditer(r'^  t(?:\.([A-Za-z]+)|\["([A-Za-z-]+)"\]) = getLookupTableFactory\(function \(t\) \{\n(.*?)^  \}\);', js, re.M | re.S):
        name = m.group(1) or m.group(2)
        widths = {}
        for w in re.finditer(r't(?:\.([A-Za-z0-9_]+)|\[("[^"]+")\]) = (\d+);', m.group(3)):
            widths[w.group(1) or key(w.group(2))] = int(w.group(3))
        fonts[name] = sorted(widths.items(), key=lambda kv: kv[0].encode())
    return fonts


def std_font_map(js):
    start = js.index("const getStdFontMap")
    body = js[start:js.index("});", start)]
    pairs = {}
    for m in re.finditer(r't(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\]) = "([^"]+)";', body):
        pairs[m.group(1) or m.group(2)] = m.group(3)
    return sorted(pairs.items(), key=lambda kv: kv[0].encode())


def main():
    texts = load(sys.argv[1] if len(sys.argv) > 1 else None)
    out = [
        "//! Font data tables, generated by scripts/generate-font-tables.py from",
        "//! pdf.js (Copyright Mozilla Foundation, Apache-2.0): the Adobe Glyph List,",
        "//! the predefined encodings, the standard 14 fonts' widths and common font",
        "//! name aliases. Do not edit by hand.",
        "",
        "/// Glyph name to Unicode, sorted by name for binary search.",
        "pub static GLYPH_LIST: &[(&str, &str)] = &[",
    ]
    out += [f"    ({rust_str(k)}, {rust_str(v)})," for k, v in glyph_list(texts["glyphlist"])]
    out += ["];", "", "/// ZapfDingbats glyph names (a1, a2…) to Unicode, sorted by name.", "pub static DINGBATS_GLYPH_LIST: &[(&str, &str)] = &["]
    out += [f"    ({rust_str(k)}, {rust_str(v)})," for k, v in dingbats_list(texts["glyphlist"])]
    out += ["];", ""]
    for rust_name, js_name in [
        ("STANDARD_ENCODING", "StandardEncoding"),
        ("WIN_ANSI_ENCODING", "WinAnsiEncoding"),
        ("MAC_ROMAN_ENCODING", "MacRomanEncoding"),
        ("MAC_EXPERT_ENCODING", "MacExpertEncoding"),
        ("SYMBOL_ENCODING", "SymbolSetEncoding"),
        ("ZAPF_DINGBATS_ENCODING", "ZapfDingbatsEncoding"),
    ]:
        names = encoding(texts["encodings"], js_name)
        out.append(f"/// `{js_name}`: glyph name per code; empty when undefined.")
        out.append(f"pub static {rust_name}: [&str; 256] = [")
        out += [f"    {rust_str(n)}," for n in names]
        out += ["];", ""]
    fonts = metrics(texts["metrics"])
    out.append("/// Glyph widths (1/1000 em) of the standard 14 fonts: a fixed width, or a")
    out.append("/// table sorted by glyph name.")
    out.append("pub static STANDARD_14_WIDTHS: &[(&str, Widths)] = &[")
    for name in sorted(fonts, key=str.encode):
        value = fonts[name]
        if isinstance(value, int):
            out.append(f"    ({rust_str(name)}, Widths::Fixed({value})),")
        else:
            out.append(f"    ({rust_str(name)}, Widths::Table(&[")
            out += [f"        ({rust_str(k)}, {v})," for k, v in value]
            out.append("    ])),")
    out += ["];", ""]
    out.append("/// Font name to the standard 14 font that substitutes for it.")
    out.append("pub static STANDARD_FONT_ALIASES: &[(&str, &str)] = &[")
    out += [f"    ({rust_str(k)}, {rust_str(v)})," for k, v in std_font_map(texts["standard_fonts"])]
    out += ["];", "", "/// Widths of one standard font.", "#[derive(Debug, Clone, Copy)]", "pub enum Widths {",
            "    /// Every glyph has this width (Courier).", "    Fixed(u16),",
            "    /// Width per glyph name, sorted by name.", "    Table(&'static [(&'static str, u16)]),", "}", ""]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path.relative_to(root)}")


if __name__ == "__main__":
    main()
