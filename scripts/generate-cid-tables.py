#!/usr/bin/env python3
"""Generate crates/otf-pdf-font/src/cid_tables.rs: CID -> Unicode for the
Adobe-Japan1, Adobe-GB1, Adobe-CNS1 and Adobe-Korea1 character collections.

They are inverted from Adobe's Unicode CMaps (UniJIS-UTF16-H, UniGB-UTF16-H,
UniCNS-UTF16-H, UniKS-UTF16-H) in adobe-type-tools/cmap-resources
(Copyright Adobe, BSD-3-Clause), pinned to a commit. A CID mapped from
several code points keeps the preferred one: unified ideographs and other
regular characters over Kangxi/CJK radicals and compatibility ideographs
(what text extraction should produce), then the lowest. Runs of consecutive CIDs mapping to
consecutive code points are stored as one range.

    scripts/generate-cid-tables.py
"""

import re
import urllib.request
from pathlib import Path

COMMIT = "f5cf3bca7fdfeaceb77aa82847e974f2306c20b4"
SOURCES = {
    "JAPAN1": "Adobe-Japan1-7/CMap/UniJIS-UTF16-H",
    "GB1": "Adobe-GB1-6/CMap/UniGB-UTF16-H",
    "CNS1": "Adobe-CNS1-7/CMap/UniCNS-UTF16-H",
    "KOREA1": "Adobe-Korea1-2/CMap/UniKS-UTF16-H",
}
root = Path(__file__).resolve().parent.parent
out_path = root / "crates" / "otf-pdf-font" / "src" / "cid_tables.rs"


def utf16(hexstr):
    b = bytes.fromhex(hexstr)
    return b.decode("utf-16-be")


def parse(text):
    """CID -> code point, from cidchar and cidrange entries."""
    cid_to_cp = {}

    def rank(cp):
        variant = 0x2E80 <= cp <= 0x2FDF or 0xF900 <= cp <= 0xFAFF or 0x2F800 <= cp <= 0x2FA1F
        return (variant, cp)

    def put(cp_str, cid):
        if len(cp_str) != 1:
            return
        cp = ord(cp_str)
        if cid not in cid_to_cp or rank(cp) < rank(cid_to_cp[cid]):
            cid_to_cp[cid] = cp

    for block in re.findall(r"begincidchar(.*?)endcidchar", text, re.S):
        for code, cid in re.findall(r"<([0-9a-fA-F]+)>\s+(\d+)", block):
            put(utf16(code), int(cid))
    for block in re.findall(r"begincidrange(.*?)endcidrange", text, re.S):
        for lo, hi, cid in re.findall(r"<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s+(\d+)", block):
            lo_s, hi_s = utf16(lo), utf16(hi)
            if len(lo_s) != 1 or len(hi_s) != 1:
                continue
            for k in range(ord(hi_s) - ord(lo_s) + 1):
                put(chr(ord(lo_s) + k), int(cid) + k)
    return cid_to_cp


def ranges(cid_to_cp):
    out = []
    for cid in sorted(cid_to_cp):
        cp = cid_to_cp[cid]
        if out:
            start_cid, start_cp, length = out[-1]
            if cid == start_cid + length and cp == start_cp + length and length < 65535:
                out[-1] = (start_cid, start_cp, length + 1)
                continue
        out.append((cid, cp, 1))
    return out


def main():
    lines = [
        "//! CID → Unicode for the Adobe CJK character collections, generated by",
        "//! scripts/generate-cid-tables.py from Adobe's cmap-resources (Copyright",
        "//! 1990-2023 Adobe, BSD-3-Clause; see NOTICE). Do not edit by hand.",
        "//!",
        "//! Each entry is (first CID, first code point, run length), sorted by CID.",
        "",
    ]
    for name, path in SOURCES.items():
        url = f"https://raw.githubusercontent.com/adobe-type-tools/cmap-resources/{COMMIT}/{path}"
        text = urllib.request.urlopen(url).read().decode("latin-1")
        table = ranges(parse(text))
        lines.append(f"/// `{path}`, inverted.")
        lines.append(f"pub static {name}: &[(u32, u32, u16)] = &[")
        lines += [f"    ({c}, 0x{p:x}, {n})," for c, p, n in table]
        lines += ["];", ""]
        print(f"{name}: {len(table)} ranges")
    out_path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
